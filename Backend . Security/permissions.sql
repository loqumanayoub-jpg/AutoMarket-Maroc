-- =========================================
-- PUBLIC READ POLICY FOR CARS
-- =========================================

create policy "Anyone can view available cars"
on public.cars
for select
to anon, authenticated
using (
  status = 'available'
);


-- =========================================
-- PUBLIC READ SETTINGS
-- =========================================

create policy "Anyone can view settings"
on public.settings
for select
to anon, authenticated
using (true);


-- =========================================
-- ADMIN ACCESS TO CARS
-- =========================================

create policy "Authenticated users can insert cars"
on public.cars
for insert
to authenticated
with check (true);


create policy "Authenticated users can update cars"
on public.cars
for update
to authenticated
using (true)
with check (true);


create policy "Authenticated users can delete cars"
on public.cars
for delete
to authenticated
using (true);


-- =========================================
-- MESSAGES
-- =========================================

create policy "Anyone can send messages"
on public.messages
for insert
to anon, authenticated
with check (true);


create policy "Authenticated users can view messages"
on public.messages
for select
to authenticated
using (true);


create policy "Authenticated users can update messages"
on public.messages
for update
to authenticated
using (true)
with check (true);


create policy "Authenticated users can delete messages"
on public.messages
for delete
to authenticated
using (true);


-- =========================================
-- PROFILES
-- =========================================

create policy "Users can view own profile"
on public.profiles
for select
to authenticated
using (auth.uid() = id);


create policy "Users can update own profile"
on public.profiles
for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);