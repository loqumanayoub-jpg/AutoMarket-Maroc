-- =========================================
-- AUTOMARKET MAROC DATABASE
-- =========================================

create table public.cars (
  id bigint generated by default as identity primary key,

  brand text not null,
  model text not null,
  year integer not null,

  price numeric(12,2) not null,
  mileage integer default 0,

  fuel text not null,
  transmission text not null,
  city text not null,

  horsepower integer,
  doors integer default 5,

  vignette numeric(10,2),

  description text,

  main_image text,
  gallery jsonb default '[]'::jsonb,

  status text default 'available'
    check (status in ('available', 'sold', 'reserved')),

  inspection_status text default 'pending'
    check (inspection_status in ('pending', 'verified', 'rejected')),

  guarantee_months integer default 0,

  created_at timestamptz default now(),
  updated_at timestamptz default now()
);


-- =========================================
-- MESSAGES
-- =========================================

create table public.messages (
  id bigint generated by default as identity primary key,

  name text not null,
  phone text not null,
  email text,

  subject text,
  message text not null,

  car_id bigint references public.cars(id)
    on delete set null,

  status text default 'new'
    check (status in ('new', 'read', 'replied', 'archived')),

  created_at timestamptz default now()
);


-- =========================================
-- SETTINGS
-- =========================================

create table public.settings (
  id bigint generated by default as identity primary key,

  dealer_name text default 'AutoMarket Maroc',
  phone text,
  whatsapp text,
  email text,

  address text,
  city text,

  facebook text,
  instagram text,

  logo_url text,
  hero_image_url text,

  updated_at timestamptz default now()
);


-- =========================================
-- USERS / ADMIN PROFILES
-- =========================================

create table public.profiles (
  id uuid primary key references auth.users(id)
    on delete cascade,

  full_name text,
  role text default 'admin'
    check (role in ('admin', 'manager')),

  created_at timestamptz default now()
);


